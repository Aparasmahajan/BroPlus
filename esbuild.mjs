// Build script — bundles the Electron targets AND resolves which plugins ship.
//
// Plugin selection (ARCHITECTURE.md §A):
//   1. Read the enabled list from BRO_PLUGINS env (comma-separated) or, failing
//      that, plugins.config.json.
//   2. Validate each plugin dir + its dependsOn (from src/plugins/<id>/plugin.json).
//   3. CODEGEN src/generated/active-plugins.ts importing ONLY enabled plugins —
//      so excluded plugins are never referenced and get tree-shaken out.
//   4. Build a UI entry + copy the panel HTML for every enabled plugin that has
//      one (src/plugins/<id>/ui/panel.ts → dist/ui/<id>.js, panel.html → <id>.html).
//
// Targets:
//   main    → dist/main/index.js       (Node; electron + native deps external)
//   preload → dist/preload/bridge.js   (Node)
//   ui      → dist/ui/*.js             (browser) + copied html/css
import { build, context } from 'esbuild';
import { cp, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';

const watch = process.argv.includes('--watch');
const dev = watch || process.argv.includes('--dev');

// ---------- Plugin selection + codegen ----------

async function resolveEnabled() {
  const env = process.env.BRO_PLUGINS?.trim();
  if (env) return env.split(',').map((s) => s.trim()).filter(Boolean);
  const cfg = JSON.parse(await readFile('plugins.config.json', 'utf8'));
  return cfg.enabled ?? [];
}

async function depsOf(id) {
  const p = join('src/plugins', id, 'plugin.json');
  if (!existsSync(p)) return [];
  try {
    return JSON.parse(await readFile(p, 'utf8')).dependsOn ?? [];
  } catch {
    return [];
  }
}

async function planPlugins() {
  const enabled = await resolveEnabled();
  const set = new Set(enabled);

  for (const id of enabled) {
    if (!existsSync(join('src/plugins', id, 'main.ts'))) {
      throw new Error(`[plugins] enabled "${id}" but src/plugins/${id}/main.ts is missing`);
    }
    for (const dep of await depsOf(id)) {
      if (!set.has(dep)) {
        throw new Error(`[plugins] "${id}" dependsOn "${dep}", which is not enabled`);
      }
    }
  }

  // Which enabled plugins ship a UI panel.
  const uiEntries = {};
  for (const id of enabled) {
    if (existsSync(join('src/plugins', id, 'ui', 'panel.ts'))) {
      uiEntries[id] = `src/plugins/${id}/ui/panel.ts`;
    }
  }

  // Codegen the active-plugins registry the main process imports.
  const imports = enabled.map((id, i) => `import p${i} from '../plugins/${id}/main';`).join('\n');
  const arr = enabled.map((_, i) => `p${i}`).join(', ');
  const gen =
    `// AUTO-GENERATED by esbuild.mjs — do not edit.\n` +
    `// Enabled plugins: ${enabled.join(', ') || '(none)'}\n` +
    `import type { BroPlugin } from '../core/plugin';\n` +
    `${imports}\n` +
    `export const activePlugins: BroPlugin[] = [${arr}];\n`;
  await mkdir('src/generated', { recursive: true });
  await writeFile('src/generated/active-plugins.ts', gen);

  console.log(`[plugins] enabled: ${enabled.join(', ') || '(none)'}`);
  return { enabled, uiEntries };
}

const { uiEntries } = await planPlugins();

// ---------- esbuild targets ----------

/** @type {import('esbuild').BuildOptions} */
const common = {
  bundle: true,
  sourcemap: dev,
  minify: !dev,
  logLevel: 'info',
  define: { 'process.env.NODE_ENV': JSON.stringify(dev ? 'development' : 'production') },
};

const targets = [
  {
    ...common,
    entryPoints: { index: 'src/main/index.ts' },
    outdir: 'dist/main',
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    // electron + native/Node-centric deps resolved at runtime from node_modules.
    external: ['electron', 'undici', 'mockttp', 'better-sqlite3', '@iarna/toml'],
  },
  {
    ...common,
    entryPoints: { bridge: 'src/preload/bridge.ts' },
    outdir: 'dist/preload',
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    external: ['electron'],
  },
  {
    ...common,
    entryPoints: { index: 'src/ui/index.ts', settings: 'src/ui/settings.ts', ...uiEntries },
    outdir: 'dist/ui',
    platform: 'browser',
    format: 'iife',
    target: 'chrome120',
  },
];

async function copyStatic() {
  await mkdir('dist/ui', { recursive: true });
  // Core UI static assets.
  for (const name of await readdir('src/ui')) {
    if (name.endsWith('.html') || name.endsWith('.css')) {
      await cp(`src/ui/${name}`, `dist/ui/${name}`);
    }
  }
  // Each enabled plugin's panel.html → dist/ui/<id>.html (matches SurfaceSpec.html).
  for (const id of Object.keys(uiEntries)) {
    const html = `src/plugins/${id}/ui/panel.html`;
    if (existsSync(html)) {
      const dest = `dist/ui/${id}.html`;
      await mkdir(dirname(dest), { recursive: true });
      await cp(html, dest);
    }
  }
}

if (watch) {
  const ctxs = await Promise.all(targets.map((t) => context(t)));
  await Promise.all(ctxs.map((c) => c.watch()));
  await copyStatic();
  console.log('[esbuild] watching…');
} else {
  await Promise.all(targets.map((t) => build(t)));
  await copyStatic();
  console.log('[esbuild] build complete');
}
